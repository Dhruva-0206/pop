/** Copies ABIs from contracts/out into packages/shared/src/abi.ts. Run after `forge build`. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const pick = (file: string, name: string) =>
  JSON.parse(readFileSync(resolve(root, "contracts", "out", file, `${name}.json`), "utf8")).abi;

const out = `// GENERATED by scripts/export-abi.ts from contracts/out. Do not edit.
export const checkoutAbi = ${JSON.stringify(pick("PoPCheckout.sol", "PoPCheckout"), null, 2)} as const;

export const registryAbi = ${JSON.stringify(pick("SellerRegistry.sol", "SellerRegistry"), null, 2)} as const;
`;
writeFileSync(resolve(root, "packages", "shared", "src", "abi.ts"), out);
console.log("wrote packages/shared/src/abi.ts");
